    <summary>¿Cómo se calcula?</summary>
    <p><strong>Cobrado</strong> es el dinero que entró por pagos y abonos de los pacientes (las ventas anuladas no cuentan). Lo que quedó a crédito cuenta cuando se cobra.</p>
    <p><strong>Costo</strong> son los productos vendidos y los insumos gastados en procedimientos, al último costo de compra.</p>
    <p><strong>Gastos</strong> son los registrados en Finanzas: servicios, sueldos, laboratorio, comisiones pagadas… Las compras de insumos no se restan: ese dinero sigue en el estante hasta que se usa. Es una estimación para orientarte, no un balance contable.</p>
</details>
